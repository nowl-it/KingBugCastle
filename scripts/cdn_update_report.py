def build_diff(old, new, lang):
    """rows + details cho một ngôn ngữ (nhãn phần diff phụ thuộc ngôn ngữ)."""
    U = UI[lang]
    files = sorted(set(os.listdir(old)) | set(os.listdir(new)))
    rows, details = [], []
    for fn in files:
        pa, pb = os.path.join(old, fn), os.path.join(new, fn)
        if not os.path.exists(pa):
            rows.append((fn, "+file", "", "", ""))
            continue
        if not os.path.exists(pb):
            rows.append((fn, "-file", "", "", ""))
            continue
        sa, sb = read(pa), read(pb)
        if sa == sb:
            continue
        if fn.startswith("Strings_"):
            add, rem, ch = str_delta(old, new, fn)
            rows.append((fn, f"{len(sb)-len(sa):+d} B", f"+{len(add)} Key",
                         f"-{len(rem)} Key", f"~{len(ch)}"))
            if fn == "Strings_EN_US.xml":
                details.append((U["keys"], [
                    '<div class="kv"><div class="kk">+' +
                    "</div><div class='kk'>+".join(esc(k) for k in add) + "</div></div>",
                    '<div class="kv"><div class="kk red">-' +
                    "</div><div class='kk red'>-".join(esc(k) for k in rem) + "</div></div>",
                ] + [diff_block(ch[k][0], ch[k][1], 6, lang) for k in sorted(ch)]))
        else:
            ra, rb, add, rem, ch = id_delta(old, new, fn)
            rows.append((fn, f"{len(sb)-len(sa):+d} B",
                         f"+{len(add)} ID" if add else "",
                         f"-{len(rem)} ID" if rem else "",
                         f"~{len(ch)}" if ch else ""))
            if add or rem or ch:
                parts = []
                if add:
                    parts.append("<div class='kv'><span class='kk'>" + U["idnew"] +
                                 ", ".join(f"<b>{esc(k)}</b>" for k in add) + "</span></div>")
                if rem:
                    parts.append("<div class='kv'><span class='kk red'>" + U["idrem"] +
                                 ", ".join(esc(k) for k in rem) + "</span></div>")
                if ch:
                    for k in ch:
                        parts.append(f"<h5>{esc(fn)} · ID {esc(k)}</h5>" +
                                     diff_block(ra[k], rb[k], 60, lang))
                if not parts:
                    parts.append(diff_block(sa, sb, 80, lang))  # đổi ngoài record có ID
                details.append((fn, parts))
    return rows, details


