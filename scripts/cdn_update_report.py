def out_names(out):
    """base.html = coder VI (backward-compat) + 3 biến thể hậu tố."""
    base = out[:-5] if out.endswith(".html") else out
    names = {("coder", "vi"): out}
    for v, l, suf in VARIANTS:
        if (v, l) != ("coder", "vi"):
            names[(v, l)] = base + suf + ".html"
    return names


def tabs_html(names, view, lang):
    grp_view = "".join(
        f'<a class="tab{" act" if v == view else ""}" href="{os.path.basename(names[(v, lang)])}">{v.capitalize()}</a>'
        for v in ("coder", "player"))
    grp_lang = "".join(
        f'<a class="tab{" act" if l == lang else ""}" href="{os.path.basename(names[(view, l)])}">{l.upper()}</a>'
        for l in ("vi", "en"))
    return f'<nav class=tabs><span class=tgrp>{grp_view}</span><span class=tgrp>{grp_lang}</span></nav>'


