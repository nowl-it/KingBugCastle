ID_RE = re.compile(r"<(\w+)([^>]*?\sID=[\"']([^\"']+)[\"'][^>]*?)(/>|>(.*?)</\1>)", re.S)
STR_RE = re.compile(r"<String Key=\"([^\"]*)\">(.*?)</String>", re.S)


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def records(text):
    return {m.group(3): m.group(0) for m in ID_RE.finditer(text)}


def esc(s, n=None):
    if n:
        s = s[:n] + ("…" if len(s) > n else "")
    return html.escape(s, quote=False)


def id_delta(old, new, fn, cap=60):
    ra, rb = records(read(os.path.join(old, fn))), records(read(os.path.join(new, fn)))
    added = sorted(set(rb) - set(ra))
    removed = sorted(set(ra) - set(rb))
    changed = sorted(k for k in set(ra) & set(rb) if ra[k] != rb[k])
    return ra, rb, added, removed, changed


def str_delta(old, new, fn="Strings_EN_US.xml"):
    ka = dict(STR_RE.findall(read(os.path.join(old, fn))))
    kb = dict(STR_RE.findall(read(os.path.join(new, fn))))
    return (sorted(set(kb) - set(ka)), sorted(set(ka) - set(kb)),
            {k: (ka[k], kb[k]) for k in set(ka) & set(kb) if ka[k] != kb[k]})


def diff_block(a, b, cap=60, lang="vi"):
    lines = list(difflib.unified_diff(a.splitlines(), b.splitlines(),
                                      lineterm="", n=1))
    body = "".join(
        f'<span class="{ "dl" if l.startswith("-") else "al" if l.startswith("+") else "cl" }">'
        f"{esc(l)}</span><br>" for l in lines[:cap])
    if len(lines) > cap:
        body += f'<span class="cl">{UI[lang]["more"].format(n=len(lines) - cap)}</span>'
    return f'<pre class="udiff">{body}</pre>'


