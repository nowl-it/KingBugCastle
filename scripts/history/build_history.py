#!/usr/bin/env python3
"""Turn .tmp/corpus/index.json into the committed history artefacts.

    python3 scripts/history/extract_chats.py        # build the corpus first
    python3 scripts/history/build_history.py        # then this

Writes:
  docs/history/sessions.md   full session catalogue, chronological
  docs/history/stats.json    numbers the blog quotes
"""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / ".tmp/corpus"
OUT = ROOT / "docs/history"

SOURCE_LABEL = {
    "opencode": "opencode",
    "claude": "Claude Code",
    "codex": "Codex",
    "qoder": "Qoder",
    "antigravity": "Antigravity",
}


def main() -> int:
    index = json.loads((CORPUS / "index.json").read_text(encoding="utf-8"))
    index.sort(key=lambda r: (r.get("start") or "9999", r["source"], r["id"]))

    per_month: Counter[str] = Counter()
    per_source: Counter[str] = Counter()
    turns = tokens_in = tokens_out = 0
    for r in index:
        if r.get("start"):
            per_month[r["start"][:7]] += 1
        per_source[r["source"]] += 1
        turns += r.get("turns") or 0
        tokens_in += r.get("tokens_in") or 0
        tokens_out += r.get("tokens_out") or 0

    dated = [r["start"] for r in index if r.get("start")]
    stats = {
        "sessions": len(index),
        "turns": turns,
        "tokens_in": tokens_in,
        "tokens_out": tokens_out,
        "by_source": dict(per_source),
        "by_month": dict(sorted(per_month.items())),
        "first_session": min(dated),
        "last_session": max(dated),
    }

    lines = ["# Session catalogue", "",
             f"{len(index)} sessions harvested across five agents "
             f"({stats['first_session'][:10]} → {stats['last_session'][:10]}).", "",
             "Generated by `scripts/history/build_history.py` from "
             "`scripts/history/extract_chats.py`; the raw transcripts stay out of git.", "",
             "| date | agent | turns | title |", "|---|---|---|---|"]
    for r in index:
        title = re.sub(r"\s+", " ", (r.get("title") or "")).strip()[:90] or "-"
        title = title.replace("|", "\\|").replace("\u2014", "-").replace("\u2013", "-")
        lines.append(f"| {(r.get('start') or '?')[:10]} | {SOURCE_LABEL.get(r['source'], r['source'])} "
                     f"| {r.get('turns') or 0} | {title} |")

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "sessions.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(stats, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
