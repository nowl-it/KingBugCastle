#!/usr/bin/env python3
"""Sinh bảng: RestAPI.<X>d__N.MoveNext -> (verb, model, uri) tu .so v174.

- ScriptMethod cua script.json cho ten + RVA cua moi MoveNext.
- Relocation .rela.dyn (R_AARCH64_RELATIVE) cho cell -> addend.
- ScriptString cho addend -> literal.
- capstone: tim adrp+ldr (cell) va bl toi Web.Post/Get.
"""
import json, struct, sys
from capstone import Cs, CS_ARCH_ARM64, CS_MODE_ARM

ROOT = '/home/nowl/Code/kgc/il2cpp/v174.0.00'
SO = ROOT + '/libil2cpp_v17400.so'
data = open(SO, 'rb').read()

# --- ELF segments + rela.dyn ---
e_phoff = struct.unpack_from('<Q', data, 0x20)[0]
e_phentsize, e_phnum = struct.unpack_from('<HH', data, 0x36)
segs = []
for i in range(e_phnum):
    o = e_phoff + i * e_phentsize
    p_type, p_flags = struct.unpack_from('<II', data, o)
    p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<QQQQ', data, o + 8)
    if p_type == 1:
        segs.append((p_vaddr, p_offset, p_filesz))


def foff(vaddr):
    for va, off, sz in segs:
        if va <= vaddr < va + sz:
            return off + (vaddr - va)
    return None


e_shoff = struct.unpack_from('<Q', data, 0x28)[0]
e_shentsize, e_shnum = struct.unpack_from('<HH', data, 0x3A)
rela = {}
for i in range(e_shnum):
    o = e_shoff + i * e_shentsize
    sh_type = struct.unpack_from('<I', data, o + 4)[0]
    sh_offset, sh_size = struct.unpack_from('<QQ', data, o + 0x18)
    if sh_type != 4:  # SHT_RELA
        continue
    for j in range(sh_size // 24):
        r_offset, r_info, r_addend = struct.unpack_from('<QQq', data, sh_offset + j * 24)
        if (r_info & 0xffffffff) == 1027:  # R_AARCH64_RELATIVE
            rela[r_offset] = r_addend

sm = json.load(open(ROOT + '/script.json'))['ScriptMethod']
methods = {}
for x in sm:
    a = int(x['Address']) if not isinstance(x['Address'], str) else int(x['Address'], 16)
    methods[a] = x['Name']
strings = {}
for x in json.load(open(ROOT + '/script.json')).get('ScriptString', []):
    a = int(x['Address']) if not isinstance(x['Address'], str) else int(x['Address'], 16)
    strings[a] = x['Value']

md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
md.detail = False


def lit_at(cell):
    add = rela.get(cell)
    if add is None:
        return None
    if add in strings:
        return strings[add]
    # Il2CppString*: +0x10 = utf16 chars, +0x18 = len
    fo = foff(add)
    if fo is None:
        return None
    try:
        ln = struct.unpack_from('<i', data, fo + 0x10)[0]
        if 0 < ln < 400:
            raw = data[fo + 0x14: fo + 0x14 + ln * 2]
            return raw.decode('utf-16-le', 'replace')
    except Exception:
        pass
    return None


def scan(rva):
    fo = foff(rva)
    if fo is None:
        return None
    code = data[fo:fo + 0x400]
    cells = {}
    verb = model = None
    for ins in md.disasm(code, rva):
        if ins.mnemonic == 'adrp':
            reg = ins.op_str.split(',')[0]
            try:
                page = int(ins.op_str.split('#')[1], 16)
            except Exception:
                page = None
            cells[reg] = [page, None]
        elif ins.mnemonic == 'ldr' and '[' in ins.op_str:
            parts = ins.op_str.split(',')
            base = parts[1].strip(' []')
            if base in cells and cells[base][0] is not None and '#' in ins.op_str:
                try:
                    off = int(ins.op_str.split('#')[-1].rstrip(']'), 0)
                except Exception:
                    off = 0
                cells[ins.op_str.split(',')[0]] = [cells[base][0] + off, None]
        elif ins.mnemonic in ('bl', 'b'):
            try:
                t = int(ins.op_str.lstrip('#'), 16)
            except Exception:
                continue
            nm = methods.get(t, '')
            if 'Web$$Post' in nm or 'Web$$Get' in nm:
                verb = 'Post' if 'Web$$Post' in nm else 'Get'
                if '<' in nm:
                    model = nm.split('<', 1)[1].split('>')[0]
                break
        if ins.mnemonic == 'ret':
            break
    uri = None
    for reg, (v, _) in cells.items():
        if v is None:
            continue
        s = lit_at(v)
        if s and s.startswith('/'):
            uri = s
            break
    return verb, model, uri


rows = []
for a, nm in sorted(methods.items()):
    if not nm.startswith('Awesomepiece.RestAPI.<'):
        continue
    if not nm.endswith('$$MoveNext'):
        continue
    parent = nm[len('Awesomepiece.RestAPI.<'):].split('>')[0]
    r = scan(a)
    if r:
        verb, model, uri = r
        rows.append((parent, verb or '?', model or '?', uri or '?'))
    else:
        rows.append((parent, '?', '?', '?'))

with open('/home/nowl/Code/kgc/docs/restapi-endpoints.txt', 'w') as f:
    f.write('# RestAPI async endpoint map (v174.0.00) - generated by /tmp/opencode/restmap.py\n')
    f.write('# method\tverb\tmodel\turi\n')
    for p, v, m, u in rows:
        f.write(f'{p}\t{v}\t{m}\t{u}\n')

print('rows:', len(rows), '| uri resolved:', sum(1 for r in rows if r[3] != '?'),
      '| verb:', sum(1 for r in rows if r[1] != '?'))
for r in rows[:6]:
    print(r)
bad = [r for r in rows if r[3] == '?']
print('unresolved sample:', bad[:4])
