#!/usr/bin/env python3
"""
Compile VideoOverlay.java → DEX → C header (video_overlay_dex.h).

Usage:
    python3 server/java/gen_video_dex.py

Requirements:
    - Android SDK with build-tools (d8) and a platform android.jar
    - JDK (javac)
    - Set ANDROID_HOME if not in ~/Android/Sdk

Output:
    server/jni/video_overlay_dex.h  (byte array embedded in C header)
"""
import os, subprocess, sys, tempfile, shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
JAVA_SRC = REPO / "server" / "java" / "com" / "kgc" / "stub" / "VideoOverlay.java"
OUT_HEADER = REPO / "server" / "jni" / "video_overlay_dex.h"

def find_android_sdk():
    candidates = []
    for env_var in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        v = os.environ.get(env_var)
        if v and Path(v).exists():
            candidates.append(Path(v))
    candidates += [Path.home() / "Android" / "Sdk",
                   Path("/usr/local/lib/android/sdk"),
                   Path("/opt/android-sdk")]
    # Return the first candidate that has both platforms/ and build-tools/
    for p in candidates:
        if (p / "platforms").is_dir() and list((p / "platforms").iterdir()) \
           and (p / "build-tools").is_dir():
            return p
    # Fallback: any candidate with at least build-tools
    for p in candidates:
        if (p / "build-tools").is_dir():
            return p
    sys.exit("ERROR: Android SDK not found. Set ANDROID_HOME.")

def find_build_tools(sdk: Path):
    bt = sdk / "build-tools"
    if not bt.exists():
        sys.exit(f"ERROR: No build-tools in {sdk}")
    versions = sorted(bt.iterdir(), key=lambda d: d.name)
    return versions[-1]

def find_android_jar(sdk: Path):
    # Check the SDK's own platforms dir first, then other known locations
    search_dirs = [sdk / "platforms"]
    search_dirs += [Path.home() / "Android" / "Sdk" / "platforms",
                    Path("/opt/android-sdk/platforms")]
    for plat in search_dirs:
        if plat.is_dir():
            versions = sorted([d for d in plat.iterdir() if d.is_dir()],
                              key=lambda d: d.name)
            if versions:
                jar = versions[-1] / "android.jar"
                if jar.exists():
                    return jar
    sys.exit(f"ERROR: android.jar not found in any known SDK location")

def main():
    sdk = find_android_sdk()
    bt = find_build_tools(sdk)
    android_jar = find_android_jar(sdk)
    d8 = bt / "d8"
    if not d8.exists():
        d8 = bt / "d8.bat" if sys.platform == "win32" else d8
    print(f"SDK:        {sdk}")
    print(f"build-tools: {bt.name}")
    print(f"android.jar: {android_jar}")
    print(f"Source:     {JAVA_SRC}")

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        classes = tmp / "classes"
        classes.mkdir()
        dex_out = tmp / "dex_out"
        dex_out.mkdir()

        # 1. javac → .class
        print("\n[1/3] Compiling Java → .class ...")
        subprocess.check_call([
            "javac", "-source", "8", "-target", "8",
            "-cp", str(android_jar),
            "-d", str(classes),
            str(JAVA_SRC),
        ])
        class_files = list(classes.rglob("*.class"))
        print(f"  Generated {len(class_files)} class file(s)")

        # 2. d8 → .dex
        # d8 from modern build-tools needs Java 11+; find one if default is older
        print("[2/3] Converting .class → .dex ...")
        d8_env = os.environ.copy()
        jvm_dir = Path("/usr/lib/jvm")
        if jvm_dir.is_dir():
            for jdk in sorted(jvm_dir.iterdir(), key=lambda d: d.name, reverse=True):
                java_bin = jdk / "bin" / "java"
                if java_bin.exists() and ("17" in jdk.name or "21" in jdk.name
                                          or "26" in jdk.name or "27" in jdk.name):
                    d8_env["JAVA_HOME"] = str(jdk)
                    d8_env["PATH"] = f"{jdk}/bin:{d8_env.get('PATH', '')}"
                    print(f"  Using JAVA_HOME={jdk} for d8")
                    break
        subprocess.check_call([
            str(d8),
            "--output", str(dex_out),
            "--min-api", "24",
        ] + [str(f) for f in class_files], env=d8_env)
        dex_file = dex_out / "classes.dex"
        if not dex_file.exists():
            sys.exit("ERROR: d8 did not produce classes.dex")
        dex_bytes = dex_file.read_bytes()
        print(f"  DEX size: {len(dex_bytes)} bytes")

        # 3. Generate C header
        print(f"[3/3] Generating {OUT_HEADER.name} ...")
        lines = [
            "// Auto-generated by gen_video_dex.py — DO NOT EDIT",
            f"// Source: {JAVA_SRC.name} ({len(dex_bytes)} bytes)",
            "#ifndef VIDEO_OVERLAY_DEX_H",
            "#define VIDEO_OVERLAY_DEX_H",
            "",
            "static const unsigned char kVideoOverlayDex[] = {",
        ]
        for i in range(0, len(dex_bytes), 16):
            chunk = dex_bytes[i:i+16]
            hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
            lines.append(f"    {hex_str},")
        lines.append("};")
        lines.append(f"static const size_t kVideoOverlayDexSize = {len(dex_bytes)};")
        lines.append("")
        lines.append("#endif // VIDEO_OVERLAY_DEX_H")
        lines.append("")

        OUT_HEADER.write_text("\n".join(lines))
        print(f"  Written to {OUT_HEADER}")

    print("\nDone! Rebuild libxigncode.so with cmake (see SETUP.md).")

if __name__ == "__main__":
    main()
